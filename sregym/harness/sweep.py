"""Sweep runner (rung 2 calibration): many seeds, concurrent, resumable, rate-limit tolerant.

Layout of a sweep directory::

    <out>/sweep.json                 configuration
    <out>/episodes/seed-<n>/         per-episode run dir (trajectory.jsonl, result.json, prompt.txt)
    <out>/results/seed-<n>.json      episode result + outcome classification (written when the seed completes)
    <out>/summary.json, report.md    regenerated by ``build_report``

Resuming: re-running the same command skips seeds that already have a non-infra result.
Infra failures (service failed to start, API errors/rate limits after the SDK's own retries)
are retried with backoff and never counted as model outcomes.
"""
